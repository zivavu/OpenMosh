export type PulsarKnobKey = (typeof PULSAR_KNOBS)[number]["key"];
export type PulsarLook = Record<PulsarKnobKey, number> & { seed: number };

const TABLE_GROUPS = new Set(["listen"]);
/** The knobs the song table is built from; the rest only change how it's drawn. */
export const PULSAR_TABLE_KNOBS: PulsarKnobKey[] = [
	"flashLength",
	"snapChance",
	"snapLength",
	"morphEvery",
	"inkShare",
	"fieldShare",
	...PULSAR_KNOBS.filter((k) => TABLE_GROUPS.has(k.group)).map((k) => k.key),
];

/** Every knob, clamped, with the defaults filling what `values` lacks. */
export function pulsarLook(
	seed: number,
	values: Partial<Record<string, number>>,
): PulsarLook {
	const look = { seed: seed >>> 0 } as PulsarLook;
	for (const knob of PULSAR_KNOBS) {
		const v = values[knob.key] ?? knob.value;
		look[knob.key] = Math.min(knob.max, Math.max(knob.min, v));
	}
	return look;
}

